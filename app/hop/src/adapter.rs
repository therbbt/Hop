//! The Tauri command + event bridge. This module is deliberately dumb: it
//! owns each live `Session`, forwards commands down into it, and forwards
//! its events back out onto the Tauri event bus. It never decides protocol
//! behavior — that all lives in the `Session` implementations themselves.

use std::collections::HashMap;
use std::sync::{Arc, Mutex};
use std::time::Duration;

use bytes::Bytes;
use tauri::{AppHandle, Emitter};
use tokio::sync::mpsc;

use hop_core::session::{CommandRunner, Session, SessionEvent};

pub enum SessionCommand {
    Write(Bytes),
    Resize(u16, u16),
    Shutdown,
}

#[derive(Clone, Default)]
pub struct AppState {
    sessions: Arc<Mutex<HashMap<String, mpsc::UnboundedSender<SessionCommand>>>>,
    /// Each live session's `CommandRunner`, if its protocol has one.
    runners: Arc<Mutex<HashMap<String, Arc<dyn CommandRunner>>>>,
}

/// How long a status check may run before it counts as unknown, so a hung
/// command (or a dead connection) can't leave a button waiting forever.
const RUN_TIMEOUT: Duration = Duration::from_secs(10);

impl AppState {
    /// Construct a `Session` for `protocol` and hand it its own tokio task.
    /// `id` is generated by the *caller* (the frontend, before it invokes
    /// this at all) rather than here, so it can subscribe to `session:<id>:*`
    /// events before this function ever runs — a session's task starts
    /// emitting events (`Connecting`, then `Connected`) the instant it's
    /// spawned below, and a local shell reaches `Connected` fast enough
    /// that a listener registered only *after* this call routinely missed
    /// it, leaving its tab stuck showing "connecting" forever. Emitting to
    /// an id nobody's listening for yet is harmless — Tauri just drops it —
    /// so the fix is to guarantee the listener exists first, not to buffer
    /// events on this end. `options` carries protocol-specific connect
    /// parameters (e.g. host/auth for SSH) as JSON — this function is the
    /// only place that knows how to turn that JSON into a concrete
    /// `Session`.
    pub fn open(
        &self,
        id: String,
        protocol: &str,
        options: serde_json::Value,
        app: AppHandle,
    ) -> Result<String, String> {
        let session: Box<dyn Session> = match protocol {
            "echo" => Box::new(hop_core::echo::EchoSession::default()),
            "shell" => {
                let opts: hop_shell::ShellConnectOptions = match options {
                    serde_json::Value::Null => hop_shell::ShellConnectOptions::default(),
                    other => serde_json::from_value(other).map_err(|e| format!("invalid shell options: {e}"))?,
                };
                Box::new(hop_shell::ShellSession::new(opts))
            }
            "ssh" => {
                let opts: hop_ssh::SshConnectOptions =
                    serde_json::from_value(options).map_err(|e| format!("invalid ssh options: {e}"))?;
                Box::new(hop_ssh::SshSession::new(opts))
            }
            "serial" => {
                let opts: hop_serial::SerialConnectOptions =
                    serde_json::from_value(options).map_err(|e| format!("invalid serial options: {e}"))?;
                Box::new(hop_serial::SerialSession::new(opts))
            }
            other => return Err(format!("unknown protocol: {other}")),
        };

        let (cmd_tx, cmd_rx) = mpsc::unbounded_channel();
        self.sessions.lock().unwrap().insert(id.clone(), cmd_tx);

        let sessions = self.sessions.clone();
        let runners = self.runners.clone();
        let task_id = id.clone();
        tauri::async_runtime::spawn(async move {
            run_session(session, cmd_rx, &app, &task_id, &runners).await;
            sessions.lock().unwrap().remove(&task_id);
            runners.lock().unwrap().remove(&task_id);
        });

        Ok(id)
    }

    pub fn send(&self, session_id: &str, cmd: SessionCommand) -> Result<(), String> {
        let sessions = self.sessions.lock().unwrap();
        let tx = sessions.get(session_id).ok_or_else(|| "unknown session".to_string())?;
        tx.send(cmd).map_err(|_| "session already closed".to_string())
    }

    /// Runs `command` in `cwd` next to the session (see `CommandRunner`)
    /// and returns its exit code.
    pub async fn run_command(&self, session_id: &str, command: &str, cwd: &str) -> Result<i32, String> {
        let runner = self
            .runners
            .lock()
            .unwrap()
            .get(session_id)
            .cloned()
            .ok_or_else(|| "session can't run commands".to_string())?;
        tokio::time::timeout(RUN_TIMEOUT, runner.run(command, cwd))
            .await
            .map_err(|_| "command timed out".to_string())?
            .map_err(|e| e.to_string())
    }
}

async fn run_session(
    mut session: Box<dyn Session>,
    mut cmd_rx: mpsc::UnboundedReceiver<SessionCommand>,
    app: &AppHandle,
    id: &str,
    runners: &Mutex<HashMap<String, Arc<dyn CommandRunner>>>,
) {
    let (event_tx, mut event_rx) = mpsc::unbounded_channel();
    if let Err(e) = session.start(event_tx).await {
        emit(app, id, &SessionEvent::Error { message: e.to_string() });
        emit(app, id, &SessionEvent::Closed { reason: Some(e.to_string()) });
        return;
    }
    if let Some(runner) = session.command_runner() {
        runners.lock().unwrap().insert(id.to_string(), runner);
    }

    loop {
        tokio::select! {
            cmd = cmd_rx.recv() => {
                match cmd {
                    Some(SessionCommand::Write(data)) => {
                        if let Err(e) = session.write(data).await {
                            emit(app, id, &SessionEvent::Error { message: e.to_string() });
                        }
                    }
                    Some(SessionCommand::Resize(cols, rows)) => {
                        if let Err(e) = session.resize(cols, rows).await {
                            emit(app, id, &SessionEvent::Error { message: e.to_string() });
                        }
                    }
                    Some(SessionCommand::Shutdown) | None => {
                        let _ = session.shutdown().await;
                        break;
                    }
                }
            }
            event = event_rx.recv() => {
                match event {
                    Some(event) => {
                        let closed = matches!(event, SessionEvent::Closed { .. });
                        emit(app, id, &event);
                        if closed {
                            break;
                        }
                    }
                    None => break,
                }
            }
        }
    }
}

/// Mirrors each `SessionEvent` variant onto its own `session:<id>:<kind>`
/// channel so the frontend's `listen("session:<id>:data", ...)` matches the
/// architecture doc literally, while lifecycle events get their own channels.
fn emit(app: &AppHandle, id: &str, event: &SessionEvent) {
    let kind = match event {
        SessionEvent::Data { .. } => "data",
        SessionEvent::TitleChanged { .. } => "title",
        SessionEvent::CwdChanged { .. } => "cwd",
        SessionEvent::StateChanged { .. } => "state",
        SessionEvent::Closed { .. } => "closed",
        SessionEvent::Error { .. } => "error",
        SessionEvent::HostKeyMismatch { .. } => "host_key_mismatch",
    };
    let _ = app.emit(&format!("session:{id}:{kind}"), event);
}
